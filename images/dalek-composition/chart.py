"""Bar chart: what the curve25519-dalek verification consists of, in lines.

Usage: python3 chart.py data.json dalek-composition.svg
Data from measure_dalek.py (Lean) and translation.json (Rust spans); see data.json.
"""
import json, sys

d = json.load(open(sys.argv[1]))
out = sys.argv[2]

FONT = "'Source Sans Pro','Source Sans 3','Helvetica Neue',Helvetica,Arial,sans-serif"
INK, INK2, MUTED, GRID, SURF = "#1e293b", "#475569", "#64748b", "#e5e7eb", "#ffffff"
# Roles: grey = context; orange = read to trust; blue = checked by Lean (validated pair)
GREY, GREY_T = "#7c7b77", "url(#hatch-grey)"
ORANGE, ORANGE_T = "#eb6834", "url(#hatch-orange)"
BLUE = "#2a78d6"
AQUA = "#1baf7a"

W, H = 960, 598
X0, X1 = 300, 760            # bar area
MAX = 60000
sx = lambda v: X0 + (X1 - X0) * v / MAX
BAR = 22
k = lambda v: f"{v/1000:.1f}k"

s = []
add = s.append
add(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
    f'font-family="{FONT}">')
# Secondary parts (constant tables, repeated statements): same colour, hatched, so they
# read as "the same kind of thing" rather than as the unfilled part of a progress bar.
def hatch(pid, col):
    return (f'<pattern id="{pid}" patternUnits="userSpaceOnUse" width="7" height="7" '
            f'patternTransform="rotate(45)"><rect width="7" height="7" fill="{col}"/>'
            f'<rect width="2.5" height="7" fill="#ffffff" opacity="0.6"/></pattern>')
add('<defs>' + hatch('hatch-grey', GREY) + hatch('hatch-orange', ORANGE) + '</defs>')
add(f'<rect width="{W}" height="{H}" fill="{SURF}"/>')

# Gridlines + ticks (recessive hairlines)
top, bottom = 30, 482
for t in range(0, MAX + 1, 10000):
    x = sx(t)
    add(f'<line x1="{x}" y1="{top}" x2="{x}" y2="{bottom}" stroke="{GRID}" stroke-width="1"/>')
    add(f'<text x="{x}" y="{bottom + 18}" fill="{MUTED}" font-size="12" text-anchor="middle">'
        f'{"0" if t == 0 else f"{t//1000}K"}</text>')
add(f'<text x="{X1}" y="{bottom + 36}" fill="{MUTED}" font-size="12" text-anchor="end">lines</text>')

def segbar(y, segs):
    """segs: [(value, colour)], drawn left to right with a 2px surface gap; rounded data end."""
    x = X0
    for i, (v, col) in enumerate(segs):
        w = sx(v) - X0
        last = i == len(segs) - 1
        if last:
            r = min(4, w / 2)
            add(f'<path d="M{x},{y} H{x+w-r} Q{x+w},{y} {x+w},{y+r} V{y+BAR-r} Q{x+w},{y+BAR} {x+w-r},{y+BAR} '
                f'H{x} Z" fill="{col}"/>')
        else:
            add(f'<rect x="{x}" y="{y}" width="{max(w-2,1)}" height="{BAR}" fill="{col}"/>')
        x += w
    return x

def row(y, label, sub, segs, tip):
    add(f'<text x="{X0-14}" y="{y+15}" fill="{INK}" font-size="15" text-anchor="end">{label}</text>')
    if sub:
        add(f'<text x="{X0-14}" y="{y+31}" fill="{MUTED}" font-size="12" text-anchor="end">{sub}</text>')
    end = segbar(y, segs)
    add(f'<text x="{end+8}" y="{y+16}" fill="{INK2}" font-size="14">{tip}</text>')

def group(y, text, col):
    add(f'<rect x="20" y="{y-11}" width="10" height="10" rx="2" fill="{col}"/>')
    add(f'<text x="36" y="{y-2}" fill="{INK}" font-size="13" font-weight="600" '
        f'letter-spacing="0.04em">{text.upper()}</text>')

y = 48
group(y, "The code", GREY)
row(y + 10, "Rust, translated part", f"of the {k(d['rust_crate_code_no_tests'])}-line crate",
    [(d["rust_translated_code"], GREY), (d["rust_translated_tables"], GREY_T)],
    f'{k(d["rust_translated_code"])} code + {k(d["rust_translated_tables"])} constant tables')

y = 120
group(y, "The result", ORANGE)
row(y + 10, "Spec statements",
    f'{d["spec_statements_distinct"]} distinct, repeated per build config',
    [(d["spec_statement_lines_distinct"], ORANGE),
     (d["spec_statement_lines"] - d["spec_statement_lines_distinct"], ORANGE_T)],
    f'{k(d["spec_statement_lines"])} ({k(d["spec_statement_lines_distinct"])} distinct)')

y = 192
group(y, "Read these to trust the result", AQUA)
row(y + 10, "Definitions: dalek", "spec vocabulary",
    [(d["spec_defs_dalek"], AQUA)], k(d["spec_defs_dalek"]))
row(y + 58, "Definitions: Curve25519", "the curve, independent of dalek",
    [(d["spec_defs_curve25519"], AQUA)], k(d["spec_defs_curve25519"]))
row(y + 106, "Rust patches", "applied before translation, for Aeneas",
    [(d["rust_patch_added"] + d["rust_patch_removed"], AQUA)],
    f'{d["rust_patches"]} patches: +{d["rust_patch_added"]} / −{d["rust_patch_removed"]} lines')

y = 360
group(y, "Checked by Lean, need not be read", BLUE)
row(y + 10, "Proofs", "incl. proof-only definitions", [(d["proofs"], BLUE)], k(d["proofs"]))

y = 432
group(y, "Generated by Aeneas, need not be read", GREY)
row(y + 10, "Lean translation", "",
    [(d["lean_translation_code"], GREY), (d["lean_translation_tables"], GREY_T)],
    f'{k(d["lean_translation_code"])} code + {k(d["lean_translation_tables"])} tables')

notes = [
    f'Also used: the EllipticCurve library ({k(d["ellipticcurve_defs"])} definitions, {k(d["ellipticcurve_proofs"])} proofs). '
    'Not translated: SIMD backends and optional features.',
    'Not shown: models of subtle and zeroize (to be proven separately) and of the Rust std library (moving into Aeneas).',
    'Lines: non-blank, non-comment; imports, namespaces and axiom checks not counted.',
]
for i, t in enumerate(notes):
    add(f'<text x="20" y="{H - 16 - 18 * (len(notes) - 1) + i*18}" fill="{MUTED}" font-size="12.5">{t}</text>')
add('</svg>')
open(out, "w").write("\n".join(s))
